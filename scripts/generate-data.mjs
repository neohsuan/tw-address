/** Generate only from the checked-in, fixed-schema Chunghwa Post XML; no network or dependencies. */
import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../data/sources/zip3-chunghwa-post-1050812.xml', import.meta.url);
const target = new URL('../src/data.generated.ts', import.meta.url);
const xml = await readFile(source, 'utf8');
// This intentionally handles this dataset's flat XML schema, not arbitrary XML.
if (/<!DOCTYPE|<!ENTITY/i.test(xml)) throw new Error('XML declarations with entities are unsupported');
const decode = (value) => value.replace(/&(#x[\da-f]+|#\d+|amp|lt|gt|quot|apos);/gi, (_, entity) => {
  if (entity.startsWith('#')) {
    return String.fromCodePoint(entity[1].toLowerCase() === 'x'
      ? Number.parseInt(entity.slice(2), 16) : Number.parseInt(entity.slice(1), 10));
  }
  return { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" }[entity.toLowerCase()];
});
const recordTag = '_x0031_050429_行政區經緯度_x0028_toPost_x0029_';
const records = [...xml.matchAll(new RegExp(`<${recordTag}>([\\s\\S]*?)</${recordTag}>`, 'g'))];
const seen = new Set();
const entries = records.map(([, body]) => {
  const name = decode(body.match(/<行政區名>([^<]+)<\/行政區名>/)?.[1] ?? '').trim();
  const zip3 = body.match(/<_x0033_碼郵遞區號>(\d{3})<\/_x0033_碼郵遞區號>/)?.[1];
  const parts = name.match(/^(.+?[縣市])(.+)$/u);
  if (!parts || !zip3 || seen.has(name)) throw new Error(`Invalid or duplicate district: ${name}`);
  seen.add(name);
  return { county: parts[1], district: parts[2], zip3 };
});
if (entries.length !== 371 || (xml.match(/<行政區名>/g) ?? []).length !== 371) {
  throw new Error(`Expected exactly 371 records; found ${entries.length}`);
}
if (entries.filter((entry) => entry.county === '嘉義市' && entry.zip3 === '600').length !== 2) {
  throw new Error('Both Chiayi City districts must retain zip3 600');
}
const header = `// Generated by scripts/generate-data.mjs. Do not edit by hand.\n// Source: Chunghwa Post, 2016-08-12; https://data.gov.tw/dataset/25489\n// Government Data Open License v1.0: https://data.gov.tw/license\n// This is a transformed 3-digit district table, not the 3+3 dataset.\nimport type { DistrictRecord } from './types.js';\n\n`;
await writeFile(target, `${header}export const DISTRICTS: readonly DistrictRecord[] = ${JSON.stringify(entries, null, 2)};\n`);
console.log(`Generated ${entries.length} district records in src/data.generated.ts`);
