import { describe, expect, it } from 'vitest';
import { normalize } from '../src/index.js';

describe('normalize', () => {
  it.each([
    ['１０６台北市大安區忠孝東路４段１２之３號５Ｆ', '106臺北市大安區忠孝東路四段12之3號5樓'],
    ['台灣 台北市 大安區 忠孝東路 3 段 十二號 五樓', '臺北市大安區忠孝東路三段12號5樓'],
    ['臺灣臺中市西屯區台灣大道３段９９號', '臺中市西屯區台灣大道三段99號'],
    ['中華民國 臺灣 台南市安平區永華路二段六號', '臺南市安平區永華路二段6號'],
    ['Taiwan (R.O.C.) 106 台北市大安區和平東路２段１２號', '106臺北市大安區和平東路二段12號'],
    ['taiwan (r.o.c.) 台東縣台東市中山路１號', '臺東縣臺東市中山路1號'],
    ['106 臺灣 台北市大安區金山南路２段５５號', '106臺北市大安區金山南路二段55號'],
    ['台北縣板橋市中山路一段一號', '新北市板橋區中山路一段1號'],
    ['桃園縣中壢市中山路１號', '桃園市中壢區中山路1號'],
    ['台中縣豐原市中山路１號', '臺中市豐原區中山路1號'],
    ['台南縣永康市中山路１號', '臺南市永康區中山路1號'],
    ['高雄縣鳳山市中山路１號', '高雄市鳳山區中山路1號'],
    ['雲林縣台西鄉中山路１號', '雲林縣臺西鄉中山路1號'],
    ['屏東縣霧台鄉中山路１號', '屏東縣霧臺鄉中山路1號'],
    ['台東市中山路一號', '臺東市中山路1號'],
    ['忠孝東路3段二十三巷十二弄十二號五樓之二', '忠孝東路三段23巷12弄12號5樓之2'],
    ['中山路１２－３號５樓之２', '中山路12之3號5樓之2'],
    ['中山路十二之三號', '中山路12之3號'],
    ['中山路12號之3', '中山路12之3號'],
    ['中山路十二號之三之四', '中山路12之3之4號'],
    ['Taiwanese address', 'Taiwanese address'],
    ['Taiwan台北市大安區中山路一號', '臺北市大安區中山路1號'],
    ['符號之三', '符號之三'],
    ['中山路12號５ｆ', '中山路12號5樓'],
    ['中山路12號5 樓', '中山路12號5樓'],
    ['中山路12號Ｂ１', '中山路12號地下1樓'],
    ['中山路12號B2F', '中山路12號地下2樓'],
    ['中山路12號b3', '中山路12號地下3樓'],
    ['中山路12號地下二樓', '中山路12號地下2樓'],
    ['中山路壹段貳拾參巷壹佰零貳號', '中山路一段23巷102號'],
    ['中山路10段廿三號', '中山路十段23號'],
    ['中山路11段卅一號', '中山路十一段31號'],
    ['中山路20段一〇二號', '中山路二十段102號'],
    ['中山路101段兩號', '中山路一百零一段2號'],
    ['106-003台北市大安區金山南路2段55號', '106003臺北市大安區金山南路二段55號'],
    ['106-03台北市大安區金山南路2段55號', '10603臺北市大安區金山南路二段55號'],
    ['臺灣省臺北縣板橋市中山路一段161號', '新北市板橋區中山路一段161號'],
    ['中華民國 台灣省 台北縣板橋市中山路1號', '新北市板橋區中山路1號'],
    ['福建省金門縣金城鎮民生路60號', '金門縣金城鎮民生路60號'],
    ['209 福建省連江縣南竿鄉介壽村76號', '209連江縣南竿鄉介壽村76號'],
    ['臺灣省道1號', '臺灣省道1號'],
    ['台灣大道三段99號', '台灣大道三段99號'],
    ['中山路12號5F-二', '中山路12號5樓之2'],
    ['中山路12號5樓-2室', '中山路12號5樓之2室'],
    ['中山路12號B1-2', '中山路12號地下1樓之2'],
    ['中山路12-1號之二', '中山路12之1之2號'],
    ['中山路12之1-2號之三', '中山路12之1之2之3號'],
    ['106 12號', '106 12號'],
    ['220 14街1號', '220 14街1號'],
    ['106-003 14街1號', '106003 14街1號'],
    ['１０６ － ００３ 臺北市大安區中山路1號', '106003臺北市大安區中山路1號'],
    ['106 - 03 臺北市大安區中山路1號', '10603臺北市大安區中山路1號'],
    ['  hello\n  world  ＡＢＣ！ ', 'hello world ABC!'],
    ['', ''],
    [' \t\n ', ''],
  ])('%s → %s', (input, expected) => {
    expect(normalize(input)).toBe(expected);
    expect(normalize(expected)).toBe(expected);
  });

  it('allows preserving a numeric hyphen', () => {
    expect(normalize('１２－３號', { hyphenToZhi: false })).toBe('12-3號');
    expect(normalize('106-003台北市', { hyphenToZhi: false })).toBe('106003臺北市');
    expect(normalize('12號5F-二', { hyphenToZhi: false })).toBe('12號5樓-2');
    expect(normalize('12-1號之二', { hyphenToZhi: false })).toBe('12-1之2號');
    expect(normalize('12號5樓之二', { hyphenToZhi: false })).toBe('12號5樓之2');
    expect(normalize('12號B1-二', { hyphenToZhi: false })).toBe('12號地下1樓-2');
  });

  it('preserves digits, 台, and number words within names', () => {
    expect(normalize('台北市大安區三台路三民大樓')).toBe('臺北市大安區三台路三民大樓');
    expect(normalize('新北市八里區十三行路一號')).toBe('新北市八里區十三行路1號');
  });

  it.each(['岡山鎮路', '東港鎮路', '北區路'])('preserves district-like road name %s', (road) => {
    expect(normalize(`${road}1號`)).toBe(`${road}1號`);
    expect(normalize(`${road}一號`)).toBe(`${road}1號`);
  });

  it.each(['十二三', '一百二三', '一千二三四', '二十二三', '零十', '零百', '零萬', '一萬二萬', '一萬萬', '三2'])('preserves malformed or mixed numeral %s', (value) => {
    expect(normalize(`中山路${value}號`)).toBe(`中山路${value}號`);
    expect(normalize(`中山路${value}段1號`)).toBe(`中山路${value}段1號`);
  });

  it.each([null, undefined, 106, {}, []])('rejects non-string input %s', (input) => {
    expect(() => normalize(input as unknown as string)).toThrow(TypeError);
  });
});
